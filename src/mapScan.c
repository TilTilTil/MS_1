#define HEIGHT 7
#define WIDTH 25

int scanMap(char map[HEIGHT][WIDTH]) {
    // Print the map
    for (int i = 0; i < HEIGHT; i++) {
        for (int j = 0; j < WIDTH; j++) {
            putchar(map[i][j]);
            putchar(' '); 
        }
        putchar('\n');
    }
    return 0;
}

